const MARKER_SHARED = '# gbdev.launcher.v1 — generated by `gbdev install`; do not edit';
const MARKER_BOT_PREFIX = '# gbdev.launcher.v1 bot=';

export type LauncherState = 'missing' | 'current' | 'stale' | 'foreign';

export interface SharedLauncherPaths {
  cliHome: string;
  launcherDir: string;
  launcherPath: string;
  nodePath: string;
  cliPath: string;
  version: string;
}

export interface LauncherStatus {
  state: LauncherState;
  path: string;
  on_path: boolean;
  node_path: string;
  cli_path: string;
  expected: string;
}

const HERE = dirname(fileURLToPath(import.meta.url));

/**
 * Deepest existing ancestor of `path` (lstat); may be a non-directory.
 * On ENOENT or ENOTDIR, walk up one level at a time until an existing component
 * is found (or the filesystem root). Callers map a non-directory / forbidden
 * symlink anchor to `launcher_conflict` — never leave raw ENOTDIR to become
 * `internal_error`.
 */
function deepestExistingAncestor(path: string): { anchor: string; missing: string[] } {
  const missing: string[] = [];
  let cursor = path;
  for (;;) {
    try {
      lstatSync(cursor);
      return { anchor: cursor, missing };
    } catch (error) {
      const err = error as NodeJS.ErrnoException;
      if (err.code !== 'ENOENT' && err.code !== 'ENOTDIR') throw error;
      const parent = dirname(cursor);
      if (parent === cursor) return { anchor: cursor, missing };
      missing.unshift(basename(cursor));
      cursor = parent;
    }
  }
}

function packageVersion(): string {
  // dist/core → ../../package.json; dist/src/core (test emit) → ../../../package.json
  for (const rel of ['../../package.json', '../../../package.json']) {
    const path = join(HERE, rel);
    if (existsSync(path)) return (JSON.parse(readFileSync(path, 'utf8')) as { version: string }).version;
  }
  throw new GbdevError('config_invalid', 'Unable to read package.json version');
}

/** Absolute path to dist/cli.js (realpath). */
export function resolveCliPath(): string {
  for (const rel of ['../cli.js', '../../cli.js']) {
    const path = join(HERE, rel);
    if (existsSync(path)) return realpathSync(path);
  }
  throw new GbdevError('config_invalid', 'Unable to resolve dist/cli.js');
}

/**
 * S-M6-6: Normalize `<GBDEV_CLI_HOME>` before any install layout check or write.
 *
 * Threat model: protect the install root and its `bin/` so that *pre-existing*
 * symlinks or non-directory components under that root cannot divert gbdev into
 * creating/writing files outside the real install location or chmod'ing foreign
 * directories. `GBDEV_CLI_HOME` itself is user-supplied: symlinks in its *ancestor*
 * path are treated as user intent — realpath the deepest existing ancestor of the
 * *parent* of the install root, then append the still-missing suffix and the
 * install-root basename. The install root's final path component is never
 * followed (symlink or non-directory there ⇒ `launcher_conflict` via lstat).
 * All later checks, creates, and result paths use this normalized absolute path.
 *
 * Same-uid TOCTOU between check and mkdir/rename is out of scope (that peer can
 * already write these locations); residual races are narrowed by post-mkdir
 * lstat, fd-based fchmod, and (dev,ino) rechecks — see ensureLauncherDirs /
 * writeLauncherAtomic.
 */
export function normalizeInstallRoot(cliHome: string): string {
  const absolute = resolve(cliHome);
  const parent = dirname(absolute);
  const base = basename(absolute);
  // Filesystem root has no parent to normalize separately.
  if (parent === absolute) return absolute;

  const { anchor, missing } = deepestExistingAncestor(parent);
  let resolvedAnchor: string;
  try {
    resolvedAnchor = realpathSync(anchor);
  } catch {
    resolvedAnchor = anchor;
  }
  return missing.length === 0
    ? join(resolvedAnchor, base)
    : join(resolvedAnchor, ...missing, base);
}

export function resolveCliHome(env: NodeJS.ProcessEnv = process.env, userHome = homedir()): string {
  return normalizeInstallRoot(expandHome(env.GBDEV_CLI_HOME ?? join(userHome, '.gbdev-cli'), userHome));
}

export function sharedLauncherPaths(env: NodeJS.ProcessEnv = process.env, userHome = homedir()): SharedLauncherPaths {
  const cliHome = resolveCliHome(env, userHome);
  const launcherDir = join(cliHome, 'bin');
  return {
    cliHome,
    launcherDir,
    launcherPath: join(launcherDir, 'gbdev'),
    nodePath: process.execPath,
    cliPath: resolveCliPath(),
    version: packageVersion(),
  };
}

/** Reject paths that cannot be safely single-quote-wrapped in a shell script. */
export function assertSafeLauncherPath(path: string, label: string): void {
  if (path.includes("'") || /[\n\r\x00-\x1f\x7f]/.test(path)) {
    throw new GbdevError('config_invalid', `${label} contains characters that cannot be embedded in the launcher script`);
  }
}

export function assertNodeMajorAtLeast24(): void {
  const major = Number(process.versions.node.split('.')[0]);
  if (!Number.isFinite(major) || major < 24) {
    throw new GbdevError('config_invalid', `gbdev install requires Node 24 or newer (found ${process.version})`);
  }
}

/** Shared launcher script body — byte-stable for a given (node, cli, version). */
export function renderSharedLauncher(nodePath: string, cliPath: string, version: string): string {
  assertSafeLauncherPath(nodePath, 'node_path');
  assertSafeLauncherPath(cliPath, 'cli_path');
  return [
    '#!/bin/sh',
    MARKER_SHARED,
    `# node: ${nodePath}`,
    `# cli: ${cliPath}`,
    `# version: ${version}`,
    `exec '${nodePath}' '${cliPath}' "$@"`,
    '',
  ].join('\n');
}

/** Per-bot launcher — implemented for unit tests; wired by init in S3. */
export function renderBotLauncher(label: string, home: string, launcherDir: string): string {
  assertSafeLauncherPath(home, 'GBDEV_HOME');
  assertSafeLauncherPath(launcherDir, 'launcher_dir');
  if (label.includes("'") || /[\n\r\x00-\x1f\x7f]/.test(label)) {
    throw new GbdevError('config_invalid', 'bot label contains characters that cannot be embedded in the launcher script');
  }
  return [
    '#!/bin/sh',
    `${MARKER_BOT_PREFIX}${label} — generated by \`gbdev init\`; do not edit`,
    'unset GBDEV_CONFIG',
    `GBDEV_HOME='${home}'; export GBDEV_HOME`,
    `exec '${launcherDir}/gbdev' "$@"`,
    '',
  ].join('\n');
}

function hasOwnerExecute(mode: number): boolean {
  return (mode & 0o100) !== 0;
}

function readLauncherState(path: string, expected: string, markerLine: string): LauncherState {
  let st;
  try {
    st = lstatSync(path);
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === 'ENOENT') return 'missing';
    throw error;
  }
  if (!st.isFile() || st.isSymbolicLink()) return 'foreign';
  let content: string;
  try {
    content = readFileSync(path, 'utf8');
  } catch {
    return 'foreign';
  }
  const lines = content.split('\n');
  if (lines[0] !== '#!/bin/sh' || lines[1] !== markerLine) return 'foreign';
  if (content === expected && hasOwnerExecute(st.mode)) return 'current';
  return 'stale';
}

export function inspectSharedLauncher(paths: SharedLauncherPaths = sharedLauncherPaths(), pathEnv = process.env.PATH ?? ''): LauncherStatus {
  const expected = renderSharedLauncher(paths.nodePath, paths.cliPath, paths.version);
  const state = readLauncherState(paths.launcherPath, expected, MARKER_SHARED);
  return {
    state,
    path: paths.launcherPath,
    on_path: launcherDirOnPath(paths.launcherDir, pathEnv),
    node_path: paths.nodePath,
    cli_path: paths.cliPath,
    expected,
  };
}

export function inspectBotLauncher(path: string, label: string, home: string, launcherDir: string): LauncherState {
  const expected = renderBotLauncher(label, home, launcherDir);
  const marker = `${MARKER_BOT_PREFIX}${label} — generated by \`gbdev init\`; do not edit`;
  return readLauncherState(path, expected, marker);
}

export function launcherDirOnPath(launcherDir: string, pathEnv: string): boolean {
  let want: string;
  try {
    want = realpathSync(launcherDir);
  } catch {
    return false;
  }
  for (const entry of pathEnv.split(':')) {
    if (!entry) continue;
    try {
      if (realpathSync(entry) === want) return true;
    } catch {
      /* skip missing PATH entries */
    }
  }
  return false;
}

export const PATH_HINT = 'export PATH="$HOME/.gbdev-cli/bin:$PATH"';

function launcherConflict(message: string, path: string): never {
  throw new GbdevError('launcher_conflict', message, { path });
}

function isRealDirectory(st: Stats): boolean {
  return st.isDirectory() && !st.isSymbolicLink();
}

function segmentsBelow(anchor: string, target: string): string[] {
  if (target === anchor) return [];
  const prefix = anchor.endsWith(sep) ? anchor : anchor + sep;
  if (!target.startsWith(prefix)) {
    launcherConflict('Install path escapes normalized anchor', target);
  }
  return target.slice(prefix.length).split(sep).filter(Boolean);
}

/**
 * Refuse symlink / non-directory components under the normalized install root
 * before any mkdir/chmod/write (S-M6-6). Uses lstat (no follow). Walks from the
 * deepest existing ancestor through `cliHome` and `bin`. Error code
 * `launcher_conflict` (SPEC N13/N21; details.path = the offending component).
 * ENOTDIR is mapped to the same code. Dry-run callers must invoke this too.
 */
export function assertSafeInstallLayout(cliHome: string, launcherDir: string): void {
  const expectedBin = join(cliHome, 'bin');
  if (launcherDir !== expectedBin) {
    launcherConflict('Launcher bin path does not match install root', launcherDir);
  }

  const { anchor, missing } = deepestExistingAncestor(cliHome);
  let st: Stats;
  try {
    st = lstatSync(anchor);
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === 'ENOTDIR') {
      launcherConflict('Install path component is not a directory', anchor);
    }
    throw error;
  }
  // Anchor is an existing path component on the way to cliHome. If it is already
  // past the install root boundary (cliHome itself or a parent that must be a
  // directory for the remaining segments), it must be a real directory.
  if (missing.length === 0 || anchor === cliHome) {
    if (!isRealDirectory(st)) {
      launcherConflict(
        st.isSymbolicLink() ? 'Install root is a symbolic link' : 'Install root exists and is not a directory',
        anchor,
      );
    }
  } else if (!isRealDirectory(st)) {
    // Intermediate/ancestor component that must be a directory to hold cliHome.
    launcherConflict(
      st.isSymbolicLink() ? 'Install path component is a symbolic link' : 'Install path component is not a directory',
      anchor,
    );
  }

  let cursor = anchor;
  // Existing cliHome ⇒ only `bin` remains. Otherwise walk the missing suffix then bin.
  const toWalk = missing.length > 0 ? [...missing, 'bin'] : [...segmentsBelow(anchor, cliHome), 'bin'];

  for (const seg of toWalk) {
    cursor = join(cursor, seg);
    let component: Stats;
    try {
      component = lstatSync(cursor);
    } catch (error) {
      const err = error as NodeJS.ErrnoException;
      if (err.code === 'ENOENT') continue;
      if (err.code === 'ENOTDIR') {
        launcherConflict('Install path component is not a directory', cursor);
      }
      throw error;
    }
    if (!isRealDirectory(component)) {
      launcherConflict(
        component.isSymbolicLink()
          ? 'Install path component is a symbolic link'
          : 'Install path component is not a directory',
        cursor,
      );
    }
  }
}

/**
 * Create missing install dirs with non-recursive mkdir; chmod 0755 only
 * directories this call newly created and re-verified as real directories.
 * Residual TOCTOU (same-uid replace between mkdir and chmod) is acknowledged
 * under S-M6-6 — we re-lstat immediately after mkdir and again before chmod.
 */
export function ensureLauncherDirs(cliHome: string, launcherDir: string, beforeMkdir?: () => void): void {
  assertSafeInstallLayout(cliHome, launcherDir);
  // Test-only sync point: after checks, before any create (not a CLI option).
  beforeMkdir?.();

  const { anchor, missing } = deepestExistingAncestor(cliHome);
  let cursor = anchor;
  try {
    const st = lstatSync(cursor);
    if (!isRealDirectory(st)) {
      launcherConflict(
        st.isSymbolicLink() ? 'Install path component is a symbolic link' : 'Install path component is not a directory',
        cursor,
      );
    }
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === 'ENOTDIR') {
      launcherConflict('Install path component is not a directory', cursor);
    }
    throw error;
  }

  const toWalk = missing.length > 0
    ? [...missing, 'bin']
    : [...segmentsBelow(anchor, cliHome), 'bin'];
  const created: string[] = [];

  for (const seg of toWalk) {
    cursor = join(cursor, seg);
    let existed = false;
    try {
      const st = lstatSync(cursor);
      if (!isRealDirectory(st)) {
        launcherConflict(
          st.isSymbolicLink() ? 'Install path component is a symbolic link' : 'Install path component is not a directory',
          cursor,
        );
      }
      existed = true;
    } catch (error) {
      const err = error as NodeJS.ErrnoException;
      if (err.code === 'ENOTDIR') {
        launcherConflict('Install path component is not a directory', cursor);
      }
      if (err.code !== 'ENOENT') throw error;
    }

    if (!existed) {
      try {
        mkdirSync(cursor, { mode: 0o755 });
      } catch (error) {
        const err = error as NodeJS.ErrnoException;
        if (err.code === 'ENOTDIR') {
          launcherConflict('Install path component is not a directory', cursor);
        }
        if (err.code !== 'EEXIST') throw error;
        // EEXIST: we did not create it; verify then skip chmod ownership.
        const raced = lstatSync(cursor);
        if (!isRealDirectory(raced)) {
          launcherConflict(
            raced.isSymbolicLink() ? 'Install path component is a symbolic link' : 'Install path component is not a directory',
            cursor,
          );
        }
        continue;
      }
      // Immediate post-mkdir recheck (S-M6-6 low-cost hardening).
      let createdStat: Stats;
      try {
        createdStat = lstatSync(cursor);
      } catch (error) {
        if ((error as NodeJS.ErrnoException).code === 'ENOTDIR') {
          launcherConflict('Install path component is not a directory', cursor);
        }
        throw error;
      }
      if (!isRealDirectory(createdStat)) {
        launcherConflict(
          createdStat.isSymbolicLink() ? 'Install path component is a symbolic link' : 'Install path component is not a directory',
          cursor,
        );
      }
      created.push(cursor);
    }
  }

  for (const dir of created) {
    // Re-lstat before chmod: refuse if replaced with a symlink/non-dir (residual race).
    const st = lstatSync(dir);
    if (!isRealDirectory(st)) {
      launcherConflict(
        st.isSymbolicLink() ? 'Install path component is a symbolic link' : 'Install path component is not a directory',
        dir,
      );
    }
    chmodSync(dir, 0o755);
  }
}

/** Atomically write a launcher script (0755); parent dir must already exist; refuses symlink. */
export function writeLauncherAtomic(path: string, content: string, launcherDir?: string): void {
  let existing;
  try {
    existing = lstatSync(path);
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error;
  }
  if (existing?.isSymbolicLink()) {
    launcherConflict('Launcher path is a symbolic link', path);
  }
  if (existing && !existing.isFile()) {
    launcherConflict('Launcher path exists and is not a regular file', path);
  }

  // Record parent dir identity before writing; recheck immediately before rename
  // so a same-uid swap of bin/ for a symlink is rejected (S-M6-6 residual race).
  const parent = launcherDir ?? dirname(path);
  let parentId: { dev: number; ino: number };
  try {
    const parentStat = lstatSync(parent);
    if (!isRealDirectory(parentStat)) {
      launcherConflict(
        parentStat.isSymbolicLink() ? 'Launcher bin directory is a symbolic link' : 'Launcher bin path exists and is not a directory',
        parent,
      );
    }
    parentId = { dev: parentStat.dev, ino: parentStat.ino };
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === 'ENOTDIR') {
      launcherConflict('Launcher bin path exists and is not a directory', parent);
    }
    throw error;
  }

  const temp = join(dirname(path), `.${randomUUID()}.tmp`);
  let fd: number | undefined;
  try {
    fd = openSync(temp, constants.O_WRONLY | constants.O_CREAT | constants.O_EXCL | constants.O_NOFOLLOW, 0o755);
    writeFileSync(fd, content, 'utf8');
    fsyncSync(fd);
    // Set mode via still-open fd — do not chmodSync the temporary path (S-M6-6).
    fchmodSync(fd, 0o755);
    closeSync(fd);
    fd = undefined;

    let beforeRename: Stats;
    try {
      beforeRename = lstatSync(parent);
    } catch (error) {
      rmSync(temp, { force: true });
      if ((error as NodeJS.ErrnoException).code === 'ENOTDIR') {
        launcherConflict('Launcher bin path exists and is not a directory', parent);
      }
      throw error;
    }
    if (!isRealDirectory(beforeRename) || beforeRename.dev !== parentId.dev || beforeRename.ino !== parentId.ino) {
      rmSync(temp, { force: true });
      launcherConflict(
        beforeRename.isSymbolicLink()
          ? 'Launcher bin directory is a symbolic link'
          : 'Launcher bin directory changed during install',
        parent,
      );
    }
    renameSync(temp, path);
  } finally {
    if (fd !== undefined) closeSync(fd);
    rmSync(temp, { force: true });
  }
}

export type InstallAction = 'created' | 'updated' | 'unchanged' | 'would_create' | 'would_update';

export interface InstallResult {
  schema: 'gbdev.install.v1';
  launcher_dir: string;
  launcher_path: string;
  node_path: string;
  cli_path: string;
  version: string;
  state_before: LauncherState;
  action: InstallAction;
  on_path: boolean;
  path_hint: string;
  dry_run: boolean;
}

export interface InstallSharedLauncherOptions {
  dryRun?: boolean;
  env?: NodeJS.ProcessEnv;
  userHome?: string;
  pathEnv?: string;
  /**
   * Test-only sync point after safe-layout checks and before mkdir.
   * Not exposed as a CLI flag or public install contract field.
   */
  testBeforeMkdir?: () => void;
}

export function installSharedLauncher(options: InstallSharedLauncherOptions = {}): InstallResult {
  assertNodeMajorAtLeast24();
  const paths = sharedLauncherPaths(options.env ?? process.env, options.userHome ?? homedir());
  assertSafeLauncherPath(paths.nodePath, 'node_path');
  assertSafeLauncherPath(paths.cliPath, 'cli_path');
  // Reject symlink / non-directory layout before any create/chmod/write (incl. dry-run).
  assertSafeInstallLayout(paths.cliHome, paths.launcherDir);
  const pathEnv = options.pathEnv ?? process.env.PATH ?? '';
  const status = inspectSharedLauncher(paths, pathEnv);
  if (status.state === 'foreign') {
    throw new GbdevError('launcher_conflict', 'Launcher path exists but is not a gbdev-managed launcher', { path: paths.launcherPath });
  }
  const dryRun = options.dryRun === true;
  let action: InstallAction;
  if (status.state === 'missing') action = dryRun ? 'would_create' : 'created';
  else if (status.state === 'stale') action = dryRun ? 'would_update' : 'updated';
  else action = 'unchanged';

  if (!dryRun && action !== 'unchanged') {
    ensureLauncherDirs(paths.cliHome, paths.launcherDir, options.testBeforeMkdir);
    writeLauncherAtomic(paths.launcherPath, status.expected, paths.launcherDir);
  }

  // Recalculate on_path after a real install so a PATH entry that pointed at a
  // not-yet-created bin directory reports true. dry-run keeps pre-write semantics
  // (SPEC §7.1: on_path iff some PATH entry realpath equals launcher_dir realpath).
  const on_path = (!dryRun && action !== 'unchanged')
    ? launcherDirOnPath(paths.launcherDir, pathEnv)
    : status.on_path;

  return {
    schema: 'gbdev.install.v1',
    launcher_dir: paths.launcherDir,
    launcher_path: paths.launcherPath,
    node_path: paths.nodePath,
    cli_path: paths.cliPath,
    version: paths.version,
    state_before: status.state,
    action,
    on_path,
    path_hint: PATH_HINT,
    dry_run: dryRun,
  };
}

export interface InstallBotLauncherOptions {
  label: string;
  home: string;
  dryRun?: boolean;
  skipWrite?: boolean;
  env?: NodeJS.ProcessEnv;
  userHome?: string;
}

export interface BotLauncherInstallResult {
  path: string;
  state_before: LauncherState;
  action: InstallAction | 'none';
  expected: string;
}

/**
 * Write per-bot launcher `gbdev-<label>` using the same layout checks and atomic
 * write as the shared launcher (SPEC §7.3 / S-M6-6). Caller must have already
 * installed (or dry-run-inspected) the shared launcher when skipWrite is false.
 */
export function installBotLauncher(options: InstallBotLauncherOptions): BotLauncherInstallResult {
  assertNodeMajorAtLeast24();
  const paths = sharedLauncherPaths(options.env ?? process.env, options.userHome ?? homedir());
  assertSafeInstallLayout(paths.cliHome, paths.launcherDir);
  assertSafeLauncherPath(options.home, 'GBDEV_HOME');
  assertSafeLauncherPath(paths.launcherDir, 'launcher_dir');
  const path = join(paths.launcherDir, `gbdev-${options.label}`);
  const expected = renderBotLauncher(options.label, options.home, paths.launcherDir);
  const state = inspectBotLauncher(path, options.label, options.home, paths.launcherDir);
  if (state === 'foreign') {
    throw new GbdevError('launcher_conflict', 'Bot launcher path exists but is not a gbdev-managed launcher', { path });
  }
  const dryRun = options.dryRun === true;
  const skipWrite = options.skipWrite === true || dryRun;
  let action: InstallAction | 'none';
  if (state === 'missing') action = skipWrite ? 'would_create' : 'created';
  else if (state === 'stale') action = skipWrite ? 'would_update' : 'updated';
  else action = 'unchanged';

  if (!skipWrite && action !== 'unchanged') {
    ensureLauncherDirs(paths.cliHome, paths.launcherDir);
    writeLauncherAtomic(path, expected, paths.launcherDir);
  }

  return { path, state_before: state, action, expected };
}
