const ROOT = resolve('.');
const NODE = process.execPath;
const NODE_BIN = dirname(NODE);
const CLI = realpathSync(join(ROOT, 'dist/cli.js'));
/** Minimal PATH for spawning the CLI under test (needs this Node 24 on PATH). */
const MIN_PATH = `${NODE_BIN}:/usr/bin:/bin`;

/** SPEC §7.2 expected shared launcher body — independent of renderSharedLauncher(). */
function expectedSharedLauncher(nodePath: string, cliPath: string, version: string): string {
  return [
    '#!/bin/sh',
    '# gbdev.launcher.v1 — generated by `gbdev install`; do not edit',
    `# node: ${nodePath}`,
    `# cli: ${cliPath}`,
    `# version: ${version}`,
    `exec '${nodePath}' '${cliPath}' "$@"`,
    '',
  ].join('\n');
}

function fixture(t: { after: (fn: () => void) => void }) {
  const root = realpathSync(mkdtempSync(join(tmpdir(), 'gbdev-m6-s2-')));
  t.after(() => rmSync(root, { recursive: true, force: true, maxRetries: 5, retryDelay: 50 }));
  const home = join(root, 'home');
  const cliHome = join(root, 'cli-home');
  const config = join(root, 'config.json');
  const missingCodex = join(root, 'missing-codex');
  const missingCursor = join(root, 'missing-cursor-agent');
  mkdirSync(home, { recursive: true });
  writeFileSync(config, JSON.stringify({
    version: 1,
    allowed_repos: [],
    providers: {
      codex: { bin: missingCodex },
      cursor: { bin: missingCursor },
    },
  }));
  for (const name of ['.zshrc', '.zprofile', '.bashrc', '.profile']) {
    writeFileSync(join(root, name), `# sentinel ${name}\n`);
  }
  // Whitelist only — do not inherit process.env (CODEX_HOME, credentials, host PATH).
  const env: NodeJS.ProcessEnv = {
    PATH: MIN_PATH,
    HOME: root,
    GBDEV_HOME: home,
    GBDEV_CONFIG: config,
    GBDEV_CLI_HOME: cliHome,
  };
  const run = (args: string[], extra: Partial<NodeJS.ProcessEnv> = {}) => {
    const result = spawnSync(NODE, [CLI, ...args], {
      encoding: 'utf8',
      env: { ...env, ...extra },
    });
    return result;
  };
  const runJson = (args: string[], extra: Partial<NodeJS.ProcessEnv> = {}) => {
    const result = run([...args, '--json'], extra);
    assert.equal(result.stderr, '', result.stderr);
    const envelope = validateEnvelope(JSON.parse(result.stdout));
    return { ...result, envelope };
  };
  const rcSnapshot = () => Object.fromEntries(
    ['.zshrc', '.zprofile', '.bashrc', '.profile'].map(n => [n, readFileSync(join(root, n))]),
  );
  return { root, home, cliHome, config, env, run, runJson, rcSnapshot, launcherPath: join(cliHome, 'bin', 'gbdev') };
}

test('AC-9 install creates launcher; second call unchanged and mtime stable', t => {
  const f = fixture(t);
  const beforeRc = f.rcSnapshot();
  const first = f.runJson(['install']);
  assert.equal(first.status, 0, first.stderr || first.stdout);
  assert.ok(first.envelope.ok);
  const result = validateInstallResult(unwrap(first.envelope));
  assert.equal(result.state_before, 'missing');
  assert.equal(result.action, 'created');
  assert.equal(result.dry_run, false);
  assert.equal(result.path_hint, PATH_HINT);
  assert.equal(result.launcher_path, f.launcherPath);
  const st = lstatSync(f.launcherPath);
  assert.ok(st.isFile());
  assert.ok(!st.isSymbolicLink());
  assert.equal(st.mode & 0o777, 0o755);
  const binDir = join(f.cliHome, 'bin');
  assert.equal(lstatSync(binDir).mode & 0o777, 0o755);
  assert.equal(lstatSync(f.cliHome).mode & 0o777, 0o755);
  const expected = expectedSharedLauncher(result.node_path, result.cli_path, result.version);
  assert.equal(readFileSync(f.launcherPath, 'utf8'), expected);
  const mtimeMs = st.mtimeMs;

  // Ensure distinguishable mtime if a rewrite incorrectly happens.
  spawnSync('sleep', ['1']);
  const second = f.runJson(['install']);
  assert.equal(second.status, 0);
  const again = validateInstallResult(unwrap(second.envelope));
  assert.equal(again.state_before, 'current');
  assert.equal(again.action, 'unchanged');
  assert.equal(statSync(f.launcherPath).mtimeMs, mtimeMs);
  assert.deepEqual(f.rcSnapshot(), beforeRc);
});

