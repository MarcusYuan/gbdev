test('AC-11 foreign file/symlink/directory → launcher_conflict with zero writes', t => {
  const f = fixture(t);
  const beforeRc = f.rcSnapshot();
  mkdirSync(join(f.cliHome, 'bin'), { recursive: true });

  const cases: { label: string; setup: () => void; snapshot: () => Buffer | 'dir' }[] = [
    {
      label: 'plain file without marker',
      setup: () => writeFileSync(f.launcherPath, '#!/bin/sh\necho foreign\n', { mode: 0o755 }),
      snapshot: () => readFileSync(f.launcherPath),
    },
    {
      label: 'symlink',
      setup: () => {
        const target = join(f.root, 'elsewhere');
        writeFileSync(target, 'target\n');
        symlinkSync(target, f.launcherPath);
      },
      snapshot: () => Buffer.from(readFileSync(f.launcherPath)),
    },
    {
      label: 'directory',
      setup: () => mkdirSync(f.launcherPath),
      snapshot: () => 'dir',
    },
  ];

  for (const c of cases) {
    rmSync(join(f.cliHome, 'bin'), { recursive: true, force: true });
    mkdirSync(join(f.cliHome, 'bin'), { recursive: true });
    c.setup();
    const before = c.snapshot();
    const beforeStat = lstatSync(f.launcherPath);
    const out = f.runJson(['install']);
    assert.equal(out.status, 1, c.label);
    assert.equal(out.envelope.ok, false);
    if (!out.envelope.ok) {
      assert.equal(out.envelope.error.code, 'launcher_conflict');
      assert.equal(out.envelope.error.details.path, f.launcherPath);
    }
    assert.deepEqual(c.snapshot(), before, c.label);
    const afterStat = lstatSync(f.launcherPath);
    assert.equal(afterStat.isSymbolicLink(), beforeStat.isSymbolicLink(), c.label);
    assert.equal(afterStat.isDirectory(), beforeStat.isDirectory(), c.label);
    assert.equal(afterStat.isFile(), beforeStat.isFile(), c.label);
  }
  assert.deepEqual(f.rcSnapshot(), beforeRc);
});

